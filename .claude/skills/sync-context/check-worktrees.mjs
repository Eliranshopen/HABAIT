#!/usr/bin/env node
/* check-worktrees.mjs — /sync-context Check 16: the worktree inventory (both repos).
 *
 *   node .claude/skills/sync-context/check-worktrees.mjs           # (re)generate §6 of docs/governance/WORKTREES.md
 *   node .claude/skills/sync-context/check-worktrees.mjs --check   # exit 0 = PASS · exit 1 = FAIL (parity) or STALE
 *
 * The table is GENERATED (the register's own schema: "rules only + the invocation that generates the live
 * inventory — not a hand-maintained table"). git answers everything measurable — path, branch, tip, last
 * commit date, dirty paths, behind/ahead of the repo's base, merged-or-not — and the ONE hand-kept half is
 * docs/governance/worktrees.json: purpose · deploy · record, keyed by the path relative to C:/RnD.
 *
 * --check reports three things and exits 1 on any of them:
 *   PARITY   a worktree on disk with no worktrees.json entry, or an entry with no worktree on disk
 *   BRANCH   an entry whose `branch` field (optional) disagrees with the live branch
 *   STALE    the committed §6 block differs from what git says now (tips move daily — regenerate, then re-check)
 * Never edits git state; never runs anything heavy. */
import fs from "node:fs";
import { execFileSync } from "node:child_process";

const BASE = "C:/RnD";
const ROOT = BASE; // the harness checkout itself (fresh department repo, 2026-11-03)
const REGISTER = `${ROOT}/docs/governance/WORKTREES.md`;
const PURPOSES = `${ROOT}/docs/governance/worktrees.json`;
const REPOS = [
  { name: "harness", dir: ROOT, base: "main" },
  { name: "app", dir: `${ROOT}/Projects/Habait/habait-walkaround`, base: "main" }, // the product repo (2026-11-03); its old origin is never used (Eliran 2026-11-03), so the base is local main
];
const BEGIN = "<!-- worktrees:begin — GENERATED by .claude/skills/sync-context/check-worktrees.mjs; never hand-edit this block; purposes live in worktrees.json -->";
const END = "<!-- worktrees:end -->";
const CHECK = process.argv.includes("--check");

const git = (dir, args) => {
  try { return execFileSync("git", ["-C", dir, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim(); }
  catch { return ""; }
};
const norm = (p) => p.replace(/\\/g, "/").replace(/\/+$/, "");
const rel = (p) => { const n = norm(p); return n.toLowerCase().startsWith(BASE.toLowerCase() + "/") ? n.slice(BASE.length + 1) : n; };

function worktreesOf(repo) {
  const out = git(repo.dir, ["worktree", "list", "--porcelain"]);
  const rows = [];
  for (const block of out.split(/\r?\n\r?\n/)) {
    const lines = block.split(/\r?\n/).filter(Boolean);
    if (!lines.length) continue;
    const path = norm((lines.find((l) => l.startsWith("worktree ")) || "").slice(9));
    if (!path) continue;
    const branchLine = lines.find((l) => l.startsWith("branch "));
    const branch = branchLine ? branchLine.slice(7).replace(/^refs\/heads\//, "") : "(detached)";
    const dir = path;
    const tip = git(dir, ["rev-parse", "--short=8", "HEAD"]) || "?";
    const date = git(dir, ["log", "-1", "--format=%ad", "--date=short"]) || "?";
    const dirty = (git(dir, ["status", "--porcelain"]) || "").split(/\r?\n/).filter(Boolean).length;
    const lr = git(dir, ["rev-list", "--left-right", "--count", `${repo.base}...HEAD`]);
    const [behind, ahead] = lr ? lr.split(/\s+/) : ["?", "?"];
    let merged = "?";
    try { execFileSync("git", ["-C", dir, "merge-base", "--is-ancestor", "HEAD", repo.base], { stdio: "ignore" }); merged = "yes"; } catch { merged = "no"; }
    rows.push({ repo: repo.name, base: repo.base, path, key: rel(path), branch, tip, date, dirty, behind, ahead, merged });
  }
  return rows;
}

const purposes = JSON.parse(fs.readFileSync(PURPOSES, "utf8"));
const known = Object.keys(purposes).filter((k) => !k.startsWith("_"));
const live = REPOS.flatMap(worktreesOf).sort((a, b) => (a.repo === b.repo ? a.key.localeCompare(b.key) : a.repo === "harness" ? -1 : 1));

/* ── parity + branch ──────────────────────────────────────────────────────── */
const liveKeys = new Set(live.map((r) => r.key));
const unnamed = live.filter((r) => !purposes[r.key]).map((r) => r.key);
const dead = known.filter((k) => !liveKeys.has(k));
const branchDrift = live.filter((r) => purposes[r.key]?.branch && purposes[r.key].branch !== r.branch).map((r) => `${r.key}: json says ${purposes[r.key].branch}, live ${r.branch}`);

/* ── the block ────────────────────────────────────────────────────────────── */
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|");
const today = new Date().toISOString().slice(0, 10);
const header = [
  `## 6. Inventory — every registered worktree of both repos (generated ${today})`,
  "",
  "> One row per `git worktree list --porcelain` entry of the harness repo (`<harness-repo>`, base `main`) and the product repo (`Projects/Habait/habait-walkaround`, base `main`). Measured cells come from git at generation time; **Purpose · Deploy · Record** are the hand-kept half in [`worktrees.json`](worktrees.json). `/sync-context` Check 16 regenerates this block and fails on a worktree with no entry, an entry with no worktree, or a stale block. ⛔ Rows are not permission to prune — every removal is R7 and Eliran's act (§3, W-1).",
  "",
  "| Worktree (under `C:/RnD/`) | Repo | Branch | Purpose | Tip · last commit | Behind/ahead of base | Dirty | Merged | Deploy | Record |",
  "|---|---|---|---|---|---|---|---|---|---|",
];
const body = live.map((r) => {
  const p = purposes[r.key] || {};
  return `| \`${r.key}\` | ${r.repo} | \`${r.branch}\` | ${p.purpose ? esc(p.purpose) : "⚠ UNNAMED — add an entry to `worktrees.json`"} | \`${r.tip}\` · ${r.date} | ${r.behind}/${r.ahead} (${r.base}) | ${r.dirty} | ${r.merged} | ${p.deploy ? esc(p.deploy) : "—"} | ${p.record ? esc(p.record) : "—"} |`;
});
const counts = `> **${live.length} worktrees** — harness ${live.filter((r) => r.repo === "harness").length} · app ${live.filter((r) => r.repo === "app").length}; merged into base ${live.filter((r) => r.merged === "yes").length}; carrying dirty paths ${live.filter((r) => r.dirty > 0).length}.`;
const block = [BEGIN, ...header, ...body, "", counts, END].join("\n");

/* ── read the register ────────────────────────────────────────────────────── */
const reg = fs.readFileSync(REGISTER, "utf8");
const eol = reg.includes("\r\n") ? "\r\n" : "\n";
const bi = reg.indexOf(BEGIN), ei = reg.indexOf(END);
const current = bi >= 0 && ei > bi ? reg.slice(bi, ei + END.length).replace(/\r\n/g, "\n") : null;
/* Freshness compares the TABLE ROWS minus the two volatile cells — the harness root's own dirty count moves
   the moment this generator writes the register (self-referential), and the summary line carries the same
   number — so `Dirty` and the counts line are excluded; since 2026-10-22 (V-24) so are the `tip · date` and `behind/ahead`
   cells (any commit moves them, and the check went STALE in 8 of 16 full passes); the worktree set, branch, merged and the three
   hand-kept cells are compared exactly, and the PARITY and BRANCH-drift tests below are unchanged. */
const rowsKey = (s) => s.split("\n").filter((l) => l.startsWith("| `")).map((l) => {
  const c = l.replace(/\\\|/g, "").split("|").map((x) => x.replace(//g, "\\|").trim());
  return c.filter((_, i) => i !== 5 && i !== 6 && i !== 7).join("|");   // 2026-10-22 (V-24): the tip·date and behind/ahead cells are no longer compared (they go STALE on any commit); Dirty was already out
}).join("\n");
const stale = current === null || rowsKey(current) !== rowsKey(block);

/* ── report ───────────────────────────────────────────────────────────────── */
const fail = [];
if (unnamed.length) fail.push(`PARITY — ${unnamed.length} worktree(s) on disk with no worktrees.json entry: ${unnamed.join(", ")}`);
if (dead.length) fail.push(`PARITY — ${dead.length} worktrees.json entr(y/ies) with no worktree on disk: ${dead.join(", ")}`);
if (branchDrift.length) fail.push(`BRANCH — ${branchDrift.join("; ")}`);

if (CHECK) {
  const verdict = fail.length ? "FAIL" : stale ? "STALE" : "PASS";
  console.log(`[16] ${verdict} — worktree inventory: ${live.length} live worktrees (harness ${live.filter((r) => r.repo === "harness").length} · app ${live.filter((r) => r.repo === "app").length}) vs ${known.length} named entries · ${unnamed.length} unnamed · ${dead.length} dead · ${branchDrift.length} branch drift · §6 block ${current === null ? "ABSENT" : stale ? "stale (tips moved — regenerate without --check)" : "current"}`);
  for (const f of fail) console.log(`    ${f}`);
  console.log(`check-worktrees: ${verdict}`);
  process.exit(fail.length || stale ? 1 : 0);
}

/* ── write ────────────────────────────────────────────────────────────────── */
let next;
if (current !== null) {
  next = reg.slice(0, bi) + block.replace(/\n/g, eol) + reg.slice(ei + END.length);
} else {
  const marker = `${eol}---${eol}${eol}**Document control**`;
  const at = reg.indexOf(marker);
  const insert = `${eol}${block.replace(/\n/g, eol)}${eol}`;
  next = at >= 0 ? reg.slice(0, at) + insert + reg.slice(at) : reg + insert;
}
fs.writeFileSync(REGISTER, next);
console.log(`check-worktrees: wrote §6 — ${live.length} rows (harness ${live.filter((r) => r.repo === "harness").length} · app ${live.filter((r) => r.repo === "app").length}) · ${unnamed.length} unnamed · ${dead.length} dead entries · ${branchDrift.length} branch drift${fail.length ? "\n    " + fail.join("\n    ") : ""}`);
process.exit(fail.length ? 1 : 0);
