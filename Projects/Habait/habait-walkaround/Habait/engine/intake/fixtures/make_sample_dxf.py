#!/usr/bin/env python
"""make_sample_dxf.py <plan.json> <out.dxf> - a SYNTHETIC apartment DXF for the DXF reader's tests.

No suitable public apartment DXF with a clear licence could be fetched without a browser (card 06, 2026-11-02), so
this writes one from a hand-checked plan.json (SCHEMA.md: cm, +y down), the way an architect's CAD file is built,
in a layer convention DIFFERENT from the PDF office map (AIA/NCS-style names), so the per-office layer map is
really exercised:

  A-WALL        wall outlines (closed LWPOLYLINE per wall piece)
  A-WALL-PATT   the wall poche (solid HATCH)
  A-DOOR        door swings as an INSERT of block DOOR_SWING (leaf LINE + 90 deg ARC), scaled to the leaf width
  A-GLAZ        facade glazing (closed LWPOLYLINE per pane)
  A-FLOR-HRAL   terrace railings
  A-AREA-BDRY   room boundaries (closed LWPOLYLINE per room: the area-calculation polylines Israeli DWGs carry)
  A-ANNO-TEXT   room names (TEXT, Hebrew, UTF-8)
  A-ANNO-DIMS   aligned DIMENSION entities, face to face through the centre of each rectangular room (min-rect fill >= 0.96)
  A-FURN        the plan's fixtures (closed LWPOLYLINE), noise for the reader
  A-ANNO-NOTE   a note, noise

DXF is y-up: every point is written as (x, -y). Units: centimetres ($INSUNITS = 5). Deterministic.
Licence: generated by Habait from its own traced plan; same rights state as that plan.json (plan_meta.rights_state)."""
from __future__ import annotations

import json
import math
import sys

import ezdxf
import numpy as np
from shapely.geometry import LineString, Point, Polygon


def P(xy):
    return (float(xy[0]), -float(xy[1]))


def main(argv=None):
    argv = argv or sys.argv[1:]
    src, dst = argv[0], argv[1]
    plan = json.load(open(src, encoding="utf-8"))
    doc = ezdxf.new("R2018", setup=True)
    doc.header["$INSUNITS"] = 5
    doc.header["$MEASUREMENT"] = 1
    for name, col in (("A-WALL", 7), ("A-WALL-PATT", 8), ("A-DOOR", 3), ("A-GLAZ", 5), ("A-FLOR-HRAL", 6), ("A-AREA-BDRY", 2),
                      ("A-ANNO-TEXT", 7), ("A-ANNO-DIMS", 1), ("A-FURN", 9), ("A-ANNO-NOTE", 7)):
        doc.layers.add(name, color=col)
    msp = doc.modelspace()
    # block: unit door swing, hinge at origin, closed leaf along +x, open leaf along +y, arc between
    blk = doc.blocks.new("DOOR_SWING")
    blk.add_line((0, 0), (0, 1), dxfattribs={"layer": "0"})
    blk.add_arc((0, 0), 1, 0, 90, dxfattribs={"layer": "0"})
    for w in plan["walls"]:
        pts = [P(p) for p in w["polygon_cm"]]
        msp.add_lwpolyline(pts, close=True, dxfattribs={"layer": "A-WALL"})
        h = msp.add_hatch(color=8, dxfattribs={"layer": "A-WALL-PATT"})
        h.paths.add_polyline_path(pts, is_closed=True)
    rooms = {r["id"]: r for r in plan["rooms"]}
    for r in plan["rooms"]:
        msp.add_lwpolyline([P(p) for p in r["loop"]], close=True, dxfattribs={"layer": "A-AREA-BDRY"})
        poly = Polygon(r["loop"]).buffer(0)
        try:
            from shapely.ops import polylabel
            c = polylabel(poly, tolerance=1.0)
        except Exception:
            c = poly.representative_point()
        msp.add_text(r["name_he"], height=15, dxfattribs={"layer": "A-ANNO-TEXT", "insert": P((c.x, c.y))})
        # two face-to-face dimensions through the room centre along its min-rect axes, when the room is near-rectangular
        mr = poly.minimum_rotated_rectangle
        if poly.area / mr.area < 0.96:
            continue
        cc = list(mr.exterior.coords)
        for e in ((np.array(cc[1]) - np.array(cc[0])), (np.array(cc[2]) - np.array(cc[1]))):
            u = e / np.hypot(*e)
            ctr = np.array([poly.centroid.x, poly.centroid.y])
            line = LineString([ctr - u * 5000, ctr + u * 5000]).intersection(poly)
            segs = [s for s in getattr(line, "geoms", [line]) if s.geom_type == "LineString"]
            if not segs:
                continue
            s = min(segs, key=lambda s: s.distance(Point(ctr)))
            a, b = s.coords[0], s.coords[-1]
            d = msp.add_aligned_dim(p1=P(a), p2=P(b), distance=12, dxfattribs={"layer": "A-ANNO-DIMS"})
            d.render()
    for o in plan["openings"]:
        if o["kind"] not in ("door", "entrance_door"):
            continue
        a, b = np.array(o["a_cm"], float), np.array(o["b_cm"], float)
        w = float(np.hypot(*(b - a)))
        u = (b - a) / w
        n = np.array([-u[1], u[0]])
        # swing into the first room of the pair (or away from 'outside')
        target = next((rid for rid in o["rooms"] if rid != "outside"), None)
        side = 1.0
        if target and target in rooms:
            if not Polygon(rooms[target]["loop"]).buffer(0).contains(Point(*(a + u * w / 2 + n * 30))):
                side = -1.0
        # in DXF (y up) the block's +x must map to the closed leaf (a -> b) and +y to the open side
        ang = math.degrees(math.atan2(-(b - a)[1], (b - a)[0]))
        open_dir_dxf = np.array([n[0] * side, -n[1] * side])
        x_dxf = np.array([u[0], -u[1]])
        cross = x_dxf[0] * open_dir_dxf[1] - x_dxf[1] * open_dir_dxf[0]
        ys = 1.0 if cross > 0 else -1.0
        msp.add_blockref("DOOR_SWING", P(a), dxfattribs={"layer": "A-DOOR", "xscale": w, "yscale": w * ys, "rotation": ang})
    for p in plan.get("panes", []):
        lay = "A-FLOR-HRAL" if p["kind"] == "railing" else "A-GLAZ"
        msp.add_lwpolyline([P(q) for q in p["polygon_cm"]], close=True, dxfattribs={"layer": lay})
    for f in plan.get("fixtures", []):
        if f.get("polygon_cm"):
            msp.add_lwpolyline([P(q) for q in f["polygon_cm"]], close=True, dxfattribs={"layer": "A-FURN"})
    msp.add_text("SYNTHETIC SAMPLE - generated from a traced plan.json by make_sample_dxf.py", height=20,
                 dxfattribs={"layer": "A-ANNO-NOTE", "insert": (0, 100)})
    doc.saveas(dst)
    print(f"wrote {dst}: {len(plan['walls'])} walls, {len(plan['rooms'])} rooms, "
          f"{sum(1 for o in plan['openings'] if o['kind'] in ('door', 'entrance_door'))} doors, {len(plan.get('panes', []))} panes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
