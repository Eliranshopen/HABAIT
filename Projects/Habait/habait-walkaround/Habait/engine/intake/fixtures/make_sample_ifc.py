#!/usr/bin/env python
"""make_sample_ifc.py <plan.json> <out.ifc> - a SYNTHETIC IFC4 apartment for the IFC reader's tests.

Same reason and source as make_sample_dxf.py: no licensed public apartment IFC could be fetched without a browser,
so this builds one from a hand-checked plan.json (cm, +y down) with IfcOpenShell:

  IfcWall    one per wall polygon, extruded 290 cm (IfcExtrudedAreaSolid of the polygon)
  IfcSpace   one per room, Name = room id, LongName = the Hebrew room name, extruded 290 cm
  IfcDoor    one per door / entrance door, a 5 cm slab from hinge to closed end (no swing geometry, as in most IFC)
  IfcWindow  one per facade pane polygon, sill 0, head 290
  IfcRailing one per railing pane polygon

IFC is y-up and SI: every point is written as (x/100, -y/100) metres. Deterministic. Licence: generated by Habait
from its own traced plan; same rights state as that plan.json."""
from __future__ import annotations

import json
import sys

import ifcopenshell
import ifcopenshell.api
import numpy as np
from shapely.geometry import Polygon


def M(xy):
    return (round(float(xy[0]) / 100.0, 4), round(-float(xy[1]) / 100.0, 4))


def ring(poly_pts):
    p = Polygon(poly_pts).buffer(0)
    if p.geom_type != "Polygon":
        p = max(p.geoms, key=lambda q: q.area)
    pts = list(p.exterior.coords)[:-1]
    return [M(q) for q in pts]


def main(argv=None):
    argv = argv or sys.argv[1:]
    plan = json.load(open(argv[0], encoding="utf-8"))
    run = ifcopenshell.api.run
    f = ifcopenshell.file(schema="IFC4")
    proj = run("root.create_entity", f, ifc_class="IfcProject", name="Habait synthetic sample")
    run("unit.assign_unit", f)
    ctx = run("context.add_context", f, context_type="Model")
    body = run("context.add_context", f, context_type="Model", context_identifier="Body", target_view="MODEL_VIEW", parent=ctx)
    site = run("root.create_entity", f, ifc_class="IfcSite", name="site")
    run("aggregate.assign_object", f, relating_object=proj, products=[site])
    bld = run("root.create_entity", f, ifc_class="IfcBuilding", name="building")
    run("aggregate.assign_object", f, relating_object=site, products=[bld])
    st = run("root.create_entity", f, ifc_class="IfcBuildingStorey", name="Floor 16")
    run("aggregate.assign_object", f, relating_object=bld, products=[st])
    h = (plan.get("plan_meta", {}).get("ceiling_height_cm") or 290) / 100.0

    def add(cls, name, pts, depth, long_name=None):
        e = run("root.create_entity", f, ifc_class=cls, name=name)
        if long_name is not None and hasattr(e, "LongName"):
            e.LongName = long_name
        rep = run("geometry.add_slab_representation", f, context=body, depth=depth, polyline=pts)
        run("geometry.assign_representation", f, product=e, representation=rep)
        run("geometry.edit_object_placement", f, product=e)
        if cls == "IfcSpace":
            run("aggregate.assign_object", f, relating_object=st, products=[e])
        else:
            run("spatial.assign_container", f, relating_structure=st, products=[e])
        return e

    for w in plan["walls"]:
        add("IfcWall", w["id"], ring(w["polygon_cm"]), h)
    for r in plan["rooms"]:
        add("IfcSpace", r["id"], ring(r["loop"]), h, long_name=r["name_he"])
    nd = 0
    for o in plan["openings"]:
        if o["kind"] not in ("door", "entrance_door"):
            continue
        a, b = np.array(o["a_cm"], float), np.array(o["b_cm"], float)
        u = (b - a) / np.hypot(*(b - a))
        n = np.array([-u[1], u[0]]) * 2.5
        add("IfcDoor", o["id"], [M(a - n), M(b - n), M(b + n), M(a + n)], 2.15)
        nd += 1
    for p in plan.get("panes", []):
        add("IfcRailing" if p["kind"] == "railing" else "IfcWindow", p["id"], ring(p["polygon_cm"]), 1.1 if p["kind"] == "railing" else h)
    f.write(argv[1])
    print(f"wrote {argv[1]}: {len(plan['walls'])} walls, {len(plan['rooms'])} spaces, {nd} doors, {len(plan.get('panes', []))} windows/railings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
